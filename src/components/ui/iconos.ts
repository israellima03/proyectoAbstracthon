export type NombreIcono = keyof typeof iconos;

export const esIcono = (valor: string): valor is NombreIcono => Object.hasOwn(iconos, valor);

/** Como svgIcono, pero acepta cualquier texto (p. ej. datos guardados) y usa "etiqueta" si no existe. */
export function svgIconoSeguro(valor: string, clase = "size-4", trazo = 2): string {
  return svgIcono(esIcono(valor) ? valor : "etiqueta", clase, trazo);
}

/** Devuelve el SVG como texto (para usar desde scripts del navegador). */
export function svgIcono(nombre: NombreIcono, clase = "size-5", trazo = 2): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${trazo}" stroke-linecap="round" stroke-linejoin="round" class="${clase}" aria-hidden="true">${iconos[nombre]}</svg>`;
}
